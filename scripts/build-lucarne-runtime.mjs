// Bundles widget/lucarne-runtime.ts (the page runtime vibewaiting delivers through Lucarne) into
// src/lucarne-runtime.generated.ts as one string, which createLucarneInjector embeds. Runs before tsc.
import { build } from "esbuild";
import { writeFileSync } from "node:fs";
const root = new URL("..", import.meta.url);
const result = await build({ entryPoints: [new URL("widget/lucarne-runtime.ts", root).pathname], bundle: true, format: "iife", minify: true, platform: "browser", target: "es2022", write: false });
const source = result.outputFiles[0]?.text;
if (!source) throw new Error("could not build the Lucarne delivery runtime");
writeFileSync(new URL("src/lucarne-runtime.generated.ts", root), `// Generated by scripts/build-lucarne-runtime.mjs from widget/lucarne-runtime.ts. Do not edit.\nexport const LUCARNE_RUNTIME_SOURCE = ${JSON.stringify(source)};\n`);
